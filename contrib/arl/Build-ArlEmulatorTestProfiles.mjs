#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const here = path.dirname(new URL(import.meta.url).pathname);
const profilesDir = path.join(here, "profiles");
const basePath = path.join(profilesDir, "impact-checksum-sweep.json");

function checksum(text) {
  let sum = 0;
  for (const ch of text) sum = (sum + ch.charCodeAt(0)) & 0xff;
  return sum;
}

function pad3(value) {
  return String(value).padStart(3, "0");
}

function parseResultLine(responseAscii) {
  const match = responseAscii.match(/^#?(.+?)\s+(\S+)\r\n?$/);
  if (!match) throw new Error(`Cannot parse result line: ${JSON.stringify(responseAscii)}`);
  return {
    fields: match[1].split(","),
    checksumText: match[2],
  };
}

function resultRule({ label, sequenceIndex, responseAscii, note, phase = "analysis-result" }) {
  const withoutPrefix = responseAscii.startsWith("#") ? responseAscii.slice(1) : responseAscii;
  const payload = withoutPrefix.replace(/\s+\S+\r\n?$/, " ");
  const checksumValue = checksum(payload);
  const checksumMatch = responseAscii.match(/\s+(\S+)\r\n?$/);
  return {
    label,
    phase,
    match: "exact_ascii",
    pattern_ascii: "#rd 246\r",
    response_ascii: responseAscii,
    repeat_policy: "sequence",
    sequence_key: "format-case-row",
    sequence_index: sequenceIndex,
    sequence_next: sequenceIndex + 1,
    computed_checksum: checksumValue,
    checksum_text: checksumMatch ? checksumMatch[1] : "",
    checksum_valid: checksumMatch ? checksumMatch[1] === pad3(checksumValue) : false,
    note,
  };
}

function recoveryRule({ label, sequenceIndex, responseAscii }) {
  const payload = responseAscii.replace(/\s+\S+\r$/, " ");
  const checksumValue = checksum(payload);
  const checksumText = responseAscii.match(/\s+(\S+)\r$/)?.[1] ?? "";
  return {
    label,
    phase: "reject-recovery",
    match: "exact_ascii",
    pattern_ascii: "?",
    response_ascii: responseAscii,
    repeat_policy: "sequence",
    sequence_key: "format-recovery-row",
    sequence_index: sequenceIndex,
    sequence_next: sequenceIndex + 1,
    computed_checksum: checksumValue,
    checksum_text: checksumText,
    checksum_valid: checksumText === pad3(checksumValue),
    note: "Distinct low-checksum recovery row after rejected format/checksum grammar cases.",
  };
}

function cloneBaseProfile(name, description) {
  const base = JSON.parse(fs.readFileSync(basePath, "utf8"));
  const profile = structuredClone(base);
  profile.name = name;
  profile.description = description;
  profile.notes = [
    ...(Array.isArray(profile.notes) ? profile.notes : []),
    "Generated by contrib/arl/Build-ArlEmulatorTestProfiles.mjs.",
  ];
  profile.responses = profile.responses.filter(
    (rule) =>
      !String(rule.label ?? "").startsWith("sweep-case-") &&
      !String(rule.label ?? "").startsWith("sweep-recovery-"),
  );
  delete profile.checksum_sweep_cases;
  return profile;
}

function insertBeforeAcceptedMarker(profile, rules) {
  const insertAt = profile.responses.findIndex((rule) => rule.label === "sweep-accepted-end-marker");
  profile.responses.splice(insertAt >= 0 ? insertAt : profile.responses.length, 0, ...rules);
}

function alternatives(token) {
  const n = Number(token);
  const decimalCount = token.includes(".") ? token.split(".")[1].length : 0;
  const variants = new Set();
  const bases = [
    token,
    token.includes(".") ? token.replace(/0+$/, "").replace(/\.$/, "") : token,
    String(n),
    n.toFixed(0),
    n.toFixed(1),
    n.toFixed(2),
    n.toFixed(3),
    n.toFixed(4),
    n.toFixed(5),
    decimalCount > 0 ? n.toFixed(decimalCount + 1) : null,
    decimalCount > 0 ? n.toFixed(decimalCount + 2) : null,
  ].filter(Boolean);

  for (const base of bases) {
    if (!Number.isFinite(Number(base)) || Number(base) !== n) continue;
    const shapes = new Set([base]);
    if (base.startsWith("0.")) shapes.add(base.slice(1));
    if (base.startsWith(".")) {
      shapes.add(`0${base}`);
      shapes.add(`00${base}`);
    }
    if (/^\d/.test(base)) {
      shapes.add(`0${base}`);
      shapes.add(`00${base}`);
    }
    for (const shape of shapes) {
      for (const prefix of ["", " ", "  ", "+", " +"]) {
        const candidate = `${prefix}${shape}`;
        if (Number(candidate) === n) variants.add(candidate);
      }
    }
  }
  return [...variants];
}

function findEquivalentLine(fields, targetChecksum, preferredFamily) {
  const options = fields.map((field) =>
    alternatives(field).map((value) => ({
      value,
      delta: (checksum(value) - checksum(field) + 256) & 0xff,
      usesPlus: value.includes("+"),
      usesSpace: /^\s/.test(value),
      usesLeadingZero: /^(\s|\+|\s\+)*0\d/.test(value),
      usesTrailingPrecision: value.replace(/^[\s+]+/, "").includes(".") && value.length > field.length,
    })),
  );

  const originalPayload = `${fields.join(",")} `;
  const needed = (targetChecksum - checksum(originalPayload) + 256) & 0xff;
  const dp = new Map([[0, []]]);
  for (let i = 0; i < options.length; i += 1) {
    const next = new Map(dp);
    for (const [sumText, pathSoFar] of dp) {
      const sum = Number(sumText);
      for (const option of options[i]) {
        const nextSum = (sum + option.delta) & 0xff;
        if (!next.has(nextSum)) next.set(nextSum, [...pathSoFar, [i, option]]);
      }
    }
    dp.clear();
    for (const [key, value] of next) dp.set(key, value);
  }

  const path = dp.get(needed);
  if (!path) return null;

  const changed = fields.slice();
  for (const [index, option] of path) changed[index] = option.value;

  const payload = `${changed.join(",")} `;
  if (checksum(payload) !== targetChecksum) throw new Error("Internal checksum search error");

  const families = new Set();
  for (const [, option] of path) {
    if (option.usesPlus) families.add("plus");
    if (option.usesSpace) families.add("leading-space");
    if (option.usesLeadingZero) families.add("leading-zero");
    if (option.usesTrailingPrecision) families.add("precision");
  }
  if (preferredFamily && !families.has(preferredFamily)) return null;

  return {
    responseAscii: `#${payload}${pad3(targetChecksum)}\r`,
    changes: path.length,
    families: [...families].sort(),
  };
}

function buildFormatEquivalenceProfile() {
  const profile = cloneBaseProfile(
    "impact-format-equivalence-sweep",
    "IMPACT emulator sweep that keeps numeric result values equivalent while changing ASCII formatting to target accepted checksums.",
  );

  const sourceByLabel = new Map(
    JSON.parse(fs.readFileSync(basePath, "utf8")).responses.map((rule) => [rule.label, rule]),
  );
  const bases = [
    ["100", "sweep-case-02-valid-decimal100"],
    ["101", "sweep-case-03-valid-decimal101"],
    ["117", "sweep-case-10-valid-decimal117"],
    ["231", "sweep-case-13-valid-decimal231"],
  ];
  const targetPlan = [
    [0, ""],
    [23, ""],
    [55, ""],
    [89, ""],
    [99, ""],
  ];

  const cases = [];
  let sequenceIndex = 0;
  for (const [baseName, label] of bases) {
    const source = sourceByLabel.get(label);
    const parsed = parseResultLine(source.response_ascii);
    cases.push(
      resultRule({
        label: `format-control-${baseName}-original-${parsed.checksumText}`,
        sequenceIndex: sequenceIndex++,
        responseAscii: source.response_ascii,
        note: "Known-rejected control row from the checksum sweep.",
      }),
    );

    for (const [targetChecksum, family] of targetPlan) {
      const found = findEquivalentLine(parsed.fields, targetChecksum, family);
      if (!found) continue;
      cases.push(
        resultRule({
          label: `format-equiv-${baseName}-to-${pad3(targetChecksum)}-${found.families.join("-") || "plain"}`,
          sequenceIndex: sequenceIndex++,
          responseAscii: found.responseAscii,
          note: `Same numeric values as ${label}; ASCII formatting changed (${found.families.join(", ") || "plain"}) to compute checksum ${pad3(targetChecksum)}.`,
        }),
      );
    }
  }

  const recoverySource = JSON.parse(fs.readFileSync(basePath, "utf8")).responses.filter((rule) =>
    String(rule.label ?? "").startsWith("sweep-recovery-"),
  );
  const recoveries = recoverySource.slice(0, Math.max(cases.length + 5, 20)).map((rule, index) =>
    recoveryRule({
      label: `format-recovery-${String(index + 1).padStart(2, "0")}-${rule.checksum_text}`,
      sequenceIndex: index,
      responseAscii: rule.response_ascii,
    }),
  );

  insertBeforeAcceptedMarker(profile, [...cases, ...recoveries]);
  profile.format_equivalence_cases = cases.map((rule) => ({
    label: rule.label,
    checksum_text: rule.checksum_text,
    checksum_valid: rule.checksum_valid,
    note: rule.note,
  }));
  return profile;
}

function replaceChecksumText(responseAscii, checksumText, delimiter = " ") {
  return responseAscii.replace(/\s+\S+\r$/, `${delimiter}${checksumText}\r`);
}

function buildChecksumGrammarProfile() {
  const profile = cloneBaseProfile(
    "impact-checksum-grammar-sweep",
    "IMPACT emulator sweep for result-row prefix, checksum width, delimiter, and line-ending grammar.",
  );
  const source = JSON.parse(fs.readFileSync(basePath, "utf8"));
  const accepted023 = source.responses.find((rule) => rule.label === "sweep-case-08-low023-shaped-distinct");
  const accepted000 = source.responses.find((rule) => rule.label === "sweep-case-09-low000-shaped-distinct");
  const rejected100 = source.responses.find((rule) => rule.label === "sweep-case-02-valid-decimal100");

  const cases = [
    ["grammar-control-023-padded-with-hash", accepted023.response_ascii, "Known accepted row."],
    ["grammar-023-no-hash", accepted023.response_ascii.slice(1), "Same row without leading #."],
    ["grammar-023-unpadded-23", replaceChecksumText(accepted023.response_ascii, "23"), "Checksum text without leading zero."],
    ["grammar-023-four-digit-0023", replaceChecksumText(accepted023.response_ascii, "0023"), "Checksum text with four digits."],
    ["grammar-023-double-space-valid-055", replaceChecksumText(accepted023.response_ascii, "055", "  "), "Double checksum delimiter; checksum recomputed with two spaces."],
    ["grammar-023-tab-valid-000", replaceChecksumText(accepted023.response_ascii, "000", "\t"), "Tab checksum delimiter; checksum recomputed with tab."],
    ["grammar-023-crlf", accepted023.response_ascii.replace(/\r$/, "\r\n"), "CRLF line ending."],
    ["grammar-control-000-padded-with-hash", accepted000.response_ascii, "Known accepted checksum 000 row."],
    ["grammar-000-no-hash", accepted000.response_ascii.slice(1), "Checksum 000 row without leading #."],
    ["grammar-000-unpadded-0", replaceChecksumText(accepted000.response_ascii, "0"), "Checksum 000 row with single digit checksum text."],
    ["grammar-control-100-rejected", rejected100.response_ascii, "Known rejected checksum 100 row."],
    ["grammar-100-four-digit-0100", replaceChecksumText(rejected100.response_ascii, "0100"), "Checksum 100 row with four digit checksum text."],
  ].map(([label, responseAscii, note], index) =>
    resultRule({ label, sequenceIndex: index, responseAscii, note, phase: "checksum-grammar" }),
  );

  const recoverySource = source.responses.filter((rule) => String(rule.label ?? "").startsWith("sweep-recovery-"));
  const recoveries = recoverySource.slice(0, 20).map((rule, index) =>
    recoveryRule({
      label: `grammar-recovery-${String(index + 1).padStart(2, "0")}-${rule.checksum_text}`,
      sequenceIndex: index,
      responseAscii: rule.response_ascii,
    }),
  );

  insertBeforeAcceptedMarker(profile, [...cases, ...recoveries]);
  profile.checksum_grammar_cases = cases.map((rule) => ({
    label: rule.label,
    checksum_text: rule.checksum_text,
    checksum_valid: rule.checksum_valid,
    note: rule.note,
  }));
  return profile;
}

function writeProfile(name, profile) {
  const output = path.join(profilesDir, name);
  fs.writeFileSync(output, `${JSON.stringify(profile, null, 2)}\n`);
  console.log(`wrote ${output}`);
}

writeProfile("impact-format-equivalence-sweep.json", buildFormatEquivalenceProfile());
writeProfile("impact-checksum-grammar-sweep.json", buildChecksumGrammarProfile());
